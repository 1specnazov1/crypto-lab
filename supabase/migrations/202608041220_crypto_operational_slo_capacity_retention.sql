create table if not exists public.crypto_operational_observations(
  id bigint generated by default as identity primary key,
  source_type text not null check(source_type in('edge','cron')),
  source_name text not null,
  observation_id text not null,
  observed_at timestamptz not null,
  success boolean not null,
  duration_ms bigint check(duration_ms is null or duration_ms>=0),
  status_code integer,
  created_at timestamptz not null default now(),
  unique(source_type,source_name,observation_id)
);

create index if not exists crypto_operational_observations_source_time_idx
on public.crypto_operational_observations(source_type,source_name,observed_at desc);
create index if not exists crypto_operational_observations_failures_idx
on public.crypto_operational_observations(observed_at desc)
where success=false;

