alter function private.get_crypto_admin_operational_summary() rename to get_crypto_admin_operational_summary_maintenance_base;
create or replace function private.get_crypto_admin_operational_summary()
returns jsonb
language plpgsql
stable
security definer
set search_path to 'public','private','pg_temp'
as $$
declare
  v_base jsonb;
  v_evidence jsonb;
  v_indicator jsonb;
  v_state text;
  v_base_state text;
  v_counts jsonb;
  v_healthy integer;
  v_warning integer;
  v_critical integer;
  v_collecting integer;
begin
  if not public.crypto_is_admin() then
    raise exception 'Admin access required' using errcode='42501';
  end if;
  v_base:=private.get_crypto_admin_operational_summary_maintenance_base();
  v_evidence:=private.get_crypto_admin_maintenance_evidence();
  v_state:=coalesce(v_evidence->>'state','critical');
  v_base_state:=coalesce(v_base->>'overall_state','critical');
  v_indicator:=jsonb_build_object(
    'code','maintenance_evidence','state',v_state,'owner','operations',
    'action_code','maintenance_evidence_runbook',
    'metrics',jsonb_build_object(
      'expected_after',v_evidence->'expected_after',
      'run_id',v_evidence#>'{maintenance_run,id}',
      'run_status',v_evidence#>'{maintenance_run,status}',
      'seal_id',v_evidence#>'{seal,id}',
      'seal_status',v_evidence#>'{seal,status}',
      'generated_at',v_evidence->'generated_at'
    )
  );
  v_counts:=coalesce(v_base->'counts','{}'::jsonb);
  v_healthy:=coalesce((v_counts->>'healthy')::integer,0)+(case when v_state='healthy' then 1 else 0 end);
  v_warning:=coalesce((v_counts->>'warning')::integer,0)+(case when v_state='warning' then 1 else 0 end);
  v_critical:=coalesce((v_counts->>'critical')::integer,0)+(case when v_state='critical' then 1 else 0 end);
  v_collecting:=coalesce((v_counts->>'collecting')::integer,0)+(case when v_state='collecting' then 1 else 0 end);
  return v_base||jsonb_build_object(
    'overall_state',case when v_base_state='critical' or v_state='critical' then 'critical'
      when v_base_state='warning' or v_state='warning' then 'warning'
      when v_base_state='collecting' or v_state='collecting' then 'collecting' else 'healthy' end,
    'decision',case when v_base_state='critical' or v_state='critical' then 'NO_GO'
      when v_base_state in('warning','collecting') or v_state in('warning','collecting') then 'WATCH' else 'TECHNICAL_GO' end,
    'counts',jsonb_build_object('healthy',v_healthy,'warning',v_warning,'critical',v_critical,'collecting',v_collecting),
    'indicators',coalesce(v_base->'indicators','[]'::jsonb)||jsonb_build_array(v_indicator),
    'alerts',case when v_state in('critical','warning') then coalesce(v_base->'alerts','[]'::jsonb)||jsonb_build_array(v_indicator) else coalesce(v_base->'alerts','[]'::jsonb) end,
    'maintenance_evidence',v_evidence
  );
end;
$$;
revoke all on function private.get_crypto_admin_operational_summary() from public,anon;
grant execute on function private.get_crypto_admin_operational_summary() to authenticated,service_role;

