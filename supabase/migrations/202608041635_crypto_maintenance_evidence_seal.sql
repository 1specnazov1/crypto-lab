create table if not exists public.crypto_maintenance_evidence_seals(
  id bigint generated by default as identity primary key,
  maintenance_run_id bigint not null unique references public.crypto_maintenance_runs(id) on delete restrict,
  manifest_id bigint not null references public.crypto_release_manifests(id) on delete restrict,
  release_checkpoint_id bigint references public.crypto_release_checkpoints(id) on delete set null,
  evidence_version integer not null default 1 check(evidence_version=1),
  expected_after timestamptz not null,
  run_started_at timestamptz not null,
  run_completed_at timestamptz,
  run_status text not null,
  counters jsonb not null default '{}'::jsonb,
  integrity_state text not null check(integrity_state in('healthy','warning','critical','collecting')),
  drift_state text not null check(drift_state in('healthy','warning','critical','collecting')),
  seal_status text not null check(seal_status in('passed','failed')),
  failure_codes jsonb not null default '[]'::jsonb check(jsonb_typeof(failure_codes)='array'),
  evidence_hash text not null unique check(evidence_hash ~ '^[0-9a-f]{64}$'),
  sealed_at timestamptz not null default now(),
  created_at timestamptz not null default now()
);

create index if not exists crypto_maintenance_evidence_seals_manifest_idx
  on public.crypto_maintenance_evidence_seals(manifest_id,sealed_at desc);
create index if not exists crypto_maintenance_evidence_seals_checkpoint_idx
  on public.crypto_maintenance_evidence_seals(release_checkpoint_id)
  where release_checkpoint_id is not null;

