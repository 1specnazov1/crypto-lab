create table if not exists public.crypto_commercial_funnel_events (
  id bigint generated by default as identity primary key,
  user_id uuid null,
  anonymous_session_hash text null check (anonymous_session_hash is null or anonymous_session_hash ~ '^[0-9a-f]{64}$'),
  event_type text not null check (event_type in ('landing_view','pricing_view','signup_started','signup_confirmed','plan_requested','checkout_started','payment_verified','subscription_activated','subscription_renewed','subscription_cancelled','support_opened')),
  source text not null default 'unknown' check (length(source) between 1 and 80),
  campaign_code text null check (campaign_code is null or campaign_code ~ '^[A-Za-z0-9_-]{1,64}$'),
  referral_code text null check (referral_code is null or referral_code ~ '^[A-Za-z0-9_-]{3,32}$'),
  metadata jsonb not null default '{}'::jsonb check (jsonb_typeof(metadata)='object'),
  occurred_at timestamptz not null default now(),
  created_at timestamptz not null default now(),
  check (user_id is not null or anonymous_session_hash is not null)
);
create index if not exists crypto_commercial_funnel_events_time_idx on public.crypto_commercial_funnel_events(occurred_at desc);
create index if not exists crypto_commercial_funnel_events_user_idx on public.crypto_commercial_funnel_events(user_id,occurred_at desc) where user_id is not null;
create index if not exists crypto_commercial_funnel_events_type_idx on public.crypto_commercial_funnel_events(event_type,occurred_at desc);

create table if not exists public.crypto_referral_program_config (
  singleton boolean primary key default true check (singleton),
  enabled boolean not null default false,
  activation_authorized boolean not null default false,
  reward_model text not null default 'owner_decision_required' check (reward_model in ('owner_decision_required','fixed','percent')),
  reward_value numeric null check (reward_value is null or reward_value >= 0),
  reward_currency text null check (reward_currency is null or reward_currency ~ '^[A-Z]{3,10}$'),
  attribution_window_days integer null check (attribution_window_days is null or attribution_window_days between 1 and 365),
  terms_version text null,
  metadata jsonb not null default '{"state":"prepared_inactive","payouts_enabled":false}'::jsonb check (jsonb_typeof(metadata)='object'),
  updated_at timestamptz not null default now(),
  check (not enabled or activation_authorized),
  check (not enabled or reward_model <> 'owner_decision_required'),
  check (not enabled or attribution_window_days is not null),
  check (reward_model='owner_decision_required' or reward_value is not null)
);
insert into public.crypto_referral_program_config(singleton) values(true) on conflict(singleton) do nothing;

create table if not exists public.crypto_referral_codes (
  code text primary key check (code ~ '^[A-Za-z0-9_-]{3,32}$'),
  owner_user_id uuid null,
  partner_label text not null check (length(btrim(partner_label)) between 1 and 120),
  status text not null default 'draft' check (status in ('draft','active','disabled')),
  metadata jsonb not null default '{}'::jsonb check (jsonb_typeof(metadata)='object'),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.crypto_referral_attributions (
  user_id uuid primary key,
  referral_code text not null references public.crypto_referral_codes(code),
  source text not null default 'registration' check (source in ('registration','account','checkout')),
  first_touch_at timestamptz not null default now(),
  attributed_at timestamptz not null default now(),
  locked boolean not null default true,
  evidence jsonb not null default '{}'::jsonb check (jsonb_typeof(evidence)='object')
);
create index if not exists crypto_referral_attributions_code_idx on public.crypto_referral_attributions(referral_code,attributed_at desc);

