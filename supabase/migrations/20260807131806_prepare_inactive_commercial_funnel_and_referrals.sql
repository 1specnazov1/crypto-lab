create or replace function private.crypto_assert_commercial_metadata_safe(p_value jsonb)
returns void language plpgsql immutable set search_path=pg_catalog,pg_temp as $$
begin
  if p_value is null or jsonb_typeof(p_value)<>'object' or length(p_value::text)>16000 then
    raise exception 'Invalid commercial metadata' using errcode='22023';
  end if;
  if lower(p_value::text) ~ '"(private_key|privatekey|seed|seed_phrase|seedphrase|mnemonic|password|wallet_password|walletpassword|authorization|access_token|refresh_token|api_key|secret|email|ip_address|raw_ip)"[[:space:]]*:' then
    raise exception 'Sensitive commercial metadata rejected' using errcode='22023';
  end if;
end;
$$;

create or replace function private.service_record_crypto_funnel_event(
  p_user_id uuid,
  p_session_hash text,
  p_event_type text,
  p_source text,
  p_campaign_code text default null,
  p_referral_code text default null,
  p_metadata jsonb default '{}'::jsonb
) returns bigint
language plpgsql security definer set search_path=public,private,auth,pg_temp as $$
declare v_id bigint;
begin
  perform private.crypto_assert_commercial_metadata_safe(coalesce(p_metadata,'{}'::jsonb));
  if p_user_id is not null and not exists(select 1 from auth.users u where u.id=p_user_id) then raise exception 'Auth user not found'; end if;
  if p_user_id is null and coalesce(p_session_hash,'') !~ '^[0-9a-f]{64}$' then raise exception 'Hashed anonymous session required'; end if;
  insert into public.crypto_commercial_funnel_events(user_id,anonymous_session_hash,event_type,source,campaign_code,referral_code,metadata)
  values(p_user_id,nullif(lower(p_session_hash),''),p_event_type,left(coalesce(nullif(btrim(p_source),''),'unknown'),80),nullif(p_campaign_code,''),nullif(p_referral_code,''),coalesce(p_metadata,'{}'::jsonb))
  returning id into v_id;
  return v_id;
end;
$$;

create or replace function private.service_attribute_crypto_referral(p_user_id uuid,p_referral_code text,p_source text default 'registration',p_evidence jsonb default '{}'::jsonb)
returns jsonb
language plpgsql security definer set search_path=public,private,auth,pg_temp as $$
declare v_config public.crypto_referral_program_config%rowtype;v_code public.crypto_referral_codes%rowtype;
begin
  perform private.crypto_assert_commercial_metadata_safe(coalesce(p_evidence,'{}'::jsonb));
  if p_user_id is null or not exists(select 1 from auth.users u where u.id=p_user_id) then raise exception 'Auth user required'; end if;
  select * into v_config from public.crypto_referral_program_config where singleton=true;
  if not coalesce(v_config.enabled,false) or not coalesce(v_config.activation_authorized,false) then raise exception 'REFERRAL_PROGRAM_DISABLED' using errcode='42501'; end if;
  select * into v_code from public.crypto_referral_codes where code=p_referral_code and status='active';
  if not found then raise exception 'REFERRAL_CODE_INACTIVE'; end if;
  insert into public.crypto_referral_attributions(user_id,referral_code,source,evidence)
  values(p_user_id,p_referral_code,p_source,coalesce(p_evidence,'{}'::jsonb))
  on conflict(user_id) do nothing;
  return jsonb_build_object('ok',true,'user_id',p_user_id,'referral_code',p_referral_code,'payout_created',false);
end;
$$;

create or replace function private.crypto_commercial_funnel_snapshot(p_days integer default 30)
returns jsonb
language sql security definer set search_path=public,pg_temp as $$
  with counts as (
    select event_type,count(*)::bigint as n
    from public.crypto_commercial_funnel_events
    where occurred_at >= now() - make_interval(days=>greatest(1,least(coalesce(p_days,30),365)))
    group by event_type
  )
  select jsonb_build_object(
    'window_days',greatest(1,least(coalesce(p_days,30),365)),
    'events',coalesce((select jsonb_object_agg(event_type,n) from counts),'{}'::jsonb),
    'total_events',(select count(*) from public.crypto_commercial_funnel_events where occurred_at >= now()-make_interval(days=>greatest(1,least(coalesce(p_days,30),365)))),
    'referral_program',(select jsonb_build_object('enabled',enabled,'activation_authorized',activation_authorized,'reward_model',reward_model,'attribution_window_days',attribution_window_days) from public.crypto_referral_program_config where singleton=true),
    'attributions',(select count(*) from public.crypto_referral_attributions)
  );
$$;

